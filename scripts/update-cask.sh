#!/bin/sh
# Writes Casks/garakuta.rb in the d0lim/tap checkout for a published release and pushes it.
# Usage: scripts/update-cask.sh 0.1.0   (the GitHub release v0.1.0 must already exist)
set -eu
VERSION="${1:?usage: update-cask.sh <version>}"
REPO="d0lim/garakuta"
ASSET="Garakuta-${VERSION}.zip"
URL="https://github.com/${REPO}/releases/download/v${VERSION}/${ASSET}"
TAP_DIR="$(brew --repo d0lim/tap)"
TMP="$(mktemp -d)"

echo "downloading ${URL}"
curl -fsSL -o "${TMP}/${ASSET}" "${URL}"
SHA="$(shasum -a 256 "${TMP}/${ASSET}" | cut -d' ' -f1)"
echo "sha256 ${SHA}"

mkdir -p "${TAP_DIR}/Casks"
cat > "${TAP_DIR}/Casks/garakuta.rb" <<RUBY
# Generated by scripts/update-cask.sh in d0lim/garakuta. Edit there, not here.
cask "garakuta" do
  version "${VERSION}"
  sha256 "${SHA}"

  url "https://github.com/${REPO}/releases/download/v#{version}/Garakuta-#{version}.zip"
  name "Garakuta"
  desc "Menu bar organizer, notch panel and window switcher"
  homepage "https://github.com/${REPO}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: :sequoia

  app "Garakuta.app"

  postflight_steps do
    # The app is ad-hoc signed, so Gatekeeper quarantines the download and refuses to open it.
    # Homebrew fetched the archive itself; clearing the flag it set is the documented way to make
    # an unsigned cask runnable.
    run "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "{{appdir}}/Garakuta.app"]
  end

  zap trash: [
    "~/Library/Application Support/Garakuta",
    "~/Library/Preferences/com.d0lim.garakuta.plist",
  ]

  caveats <<~EOS
    Garakuta needs Accessibility permission for menu bar item management and
    the window switcher. The setup assistant on first launch asks for it.
    Quit any other menu bar manager or Option-Tab switcher before enabling
    the matching Garakuta module.
  EOS
end
RUBY

cd "${TAP_DIR}"
git add Casks/garakuta.rb
git commit -q -m "${COMMIT_MESSAGE:-garakuta ${VERSION}}"
git push origin HEAD:main
echo "pushed Casks/garakuta.rb for ${VERSION}"
